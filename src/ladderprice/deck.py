"""Write presentations/ladder-pricing/deck-data.js from results/ and the per-print data in data/derived/.

    python -m ladderprice.cli deck
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

from . import evaluate

NAMES = {"KXSOLD": "SOL", "KXXRPD": "XRP", "KXDOGED": "DOGE", "KXETHD": "ETH", "POLY-SOL": "SOL (Polymarket)", "POLY-XRP": "XRP (Polymarket)"}


def _r(x, d=4):
    return None if x is None or not np.isfinite(x) else round(float(x), d)


def _score(v: dict) -> dict:
    out = {"events": v["events"], "days": v["days"], "prints": v["prints"],
           "brier": {k: _r(b, 5) for k, b in v["brier"].items()}, "auc": {k: _r(a, 3) for k, a in v["auc"].items()}}
    if "tests" in v:
        out["tests"] = {k: {kk: _r(t[kk], 5) for kk in ("est", "lo", "hi", "p_holm")} for k, t in v["tests"].items()}
    return out


def example_ladder(prints: pd.DataFrame) -> dict:
    """A busy XRP ladder: prints 5 to 8 hours before the close, with the model inputs at that time."""
    x = prints[(prints["series"] == "KXXRPD") & (prints["h"] >= 5) & (prints["h"] <= 8)]
    ev = x.groupby("event")["strike"].nunique().sort_values().index[-1]
    e = x[x["event"] == ev]
    med = e[["own_sd", "beta", "beta_down", "beta_up", "res_sd", "btc_sd", "c", "h"]].median()
    return {"event": ev, "date": str(e["day"].iloc[0])[:10], "hours": _r(med["h"], 1),
            "inputs": {k: _r(med[k], 5) for k in ("own_sd", "beta", "beta_down", "beta_up", "res_sd", "btc_sd", "c")},
            "pts": [[_r(a, 4), _r(b, 3), _r(c, 3), _r(d, 3), int(y)] for a, b, c, d, y in
                    zip(e["x"], e["p"], e["FACTOR"], e["OWN"], e["y"])][:300]}


def pnl_series(prints: pd.DataFrame) -> dict:
    out = {}
    for s in ("KXSOLD", "KXXRPD", "KXDOGED"):
        tr = evaluate.trade(prints[prints["series"] == s], "FACTOR")
        d = tr.groupby("day")[["pnl"]].sum().sort_index()
        c = d["pnl"].cumsum()
        c = c.groupby(pd.to_datetime(c.index).to_period("W")).last()
        out[s] = [[str(p.end_time.date()), _r(v / 1000, 2)] for p, v in c.items()]
    return out


def build(root: Path) -> Path:
    s = json.loads((root / "results" / "summary.json").read_text())
    prints = pd.read_csv(root / "data" / "derived" / "prints.csv.gz")
    eth = prints[prints["series"] == "KXETHD"].sample(500, random_state=0)
    payload = {
        "names": NAMES,
        "primary": _score(s["primary"]),
        "perCoin": {k: _score(v) for k, v in s["per_coin"].items()},
        "eth": _score(s["eth_check"]) | {"corr": _r(s["eth_check"]["corr_factor_ethopt"], 4)},
        "poly": {k: _score(v) for k, v in s["polymarket"]["per_coin"].items()} | {"pooled": _score(s["polymarket"]["pooled"])},
        "sens": {k: _score(v) for k, v in s["sensitivity"].items()},
        "liquidity": {k: _r(v, 0) for k, v in s["liquidity_usd_per_event"].items()},
        "trading": {k: {kk: _r(v[kk], 4) for kk in ("return", "lo", "hi", "pnl", "cost", "days")} for k, v in s["trading"].items()},
        "tradingCoin": {k: {kk: _r(v[kk], 4) for kk in ("return", "lo", "hi", "pnl", "cost", "days")} for k, v in s["trading_per_coin"].items()},
        "tradingEth": {k: {kk: _r(v[kk], 4) for kk in ("return", "lo", "hi")} for k, v in s["trading_eth"].items()},
        "tradingPoly": {k: {kk: _r(v[kk], 4) for kk in ("return", "lo", "hi")} for k, v in s["polymarket"]["trading"].items()},
        "kBtc": _r(s["meta"]["k_btc_median"], 3),
        "example": example_ladder(prints),
        "pnl": pnl_series(prints),
        "ethPts": [[_r(a, 3), _r(b, 3)] for a, b in zip(eth["ETHOPT"], eth["FACTOR"])],
    }
    out = root / "presentations" / "ladder-pricing" / "deck-data.js"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("/* Generated by `python -m ladderprice.cli deck` from results/. Do not edit by hand. */\n"
                   f"(() => {{\nconst DeckData = {json.dumps(payload, separators=(',', ':'))};\n"
                   "if (typeof module !== 'undefined') module.exports = DeckData;\nelse globalThis.DeckData = DeckData;\n})();\n")
    return out
