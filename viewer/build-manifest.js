/* Reads project.json and presentations/ at the repo root and writes viewer/manifest.js. */
const fs = require('node:fs');
const path = require('node:path');

const SLUG = /^[a-z0-9][a-z0-9-]*$/;
const readJson = (file) => {
  try {
    return JSON.parse(fs.readFileSync(file, 'utf8'));
  } catch (error) {
    throw new Error(`Could not read ${file}: ${error.message}`);
  }
};
const requireFields = (data, fields, file) => {
  fields.forEach((f) => {
    if (data[f] === undefined || data[f] === '') throw new Error(`${file} is missing "${f}"`);
  });
};
const dirs = (dir) => (fs.existsSync(dir)
  ? fs.readdirSync(dir, { withFileTypes: true }).filter((e) => e.isDirectory() && SLUG.test(e.name)).map((e) => e.name).sort()
  : []);

function buildManifest(root) {
  const projectFile = path.join(root, 'project.json');
  if (!fs.existsSync(projectFile)) return { projects: [] };
  const project = readJson(projectFile);
  requireFields(project, ['title', 'field', 'status', 'summary'], projectFile);

  const presentations = dirs(path.join(root, 'presentations')).flatMap((id) => {
    const dir = path.join(root, 'presentations', id);
    const file = path.join(dir, 'presentation.json');
    if (!fs.existsSync(file)) return [];
    const deck = readJson(file);
    requireFields(deck, ['title', 'summary', 'minutes', 'scripts'], file);
    if (!Array.isArray(deck.scripts) || deck.scripts.length === 0) throw new Error(`${file} must list at least one script`);
    deck.scripts.forEach((s) => {
      if (path.basename(s) !== s || !s.endsWith('.js')) throw new Error(`${file} has an invalid script name: ${s}`);
      if (!fs.existsSync(path.join(dir, s))) throw new Error(`${file} lists a missing script: ${s}`);
    });
    return [{ ...deck, id, order: deck.order ?? 99, path: `presentations/${id}` }];
  }).sort((a, b) => a.order - b.order || a.id.localeCompare(b.id));

  return { projects: [{ title: project.title, field: project.field, status: project.status, summary: project.summary, slug: 'project', presentations }] };
}

const renderManifest = (manifest) => `/* Generated by viewer/build-manifest.js. Do not edit by hand. */\nwindow.QUANT_MANIFEST = ${JSON.stringify(manifest, null, 2)};\n`;

function writeManifest(root) {
  const text = renderManifest(buildManifest(root));
  fs.writeFileSync(path.join(root, 'viewer', 'manifest.js'), text);
  return text;
}

if (require.main === module) {
  writeManifest(path.resolve(__dirname, '..'));
  console.log('Updated viewer/manifest.js');
}

module.exports = { buildManifest, renderManifest, writeManifest };
